-- K7 (2026-10-20): bare classic titles were cached as the first Google Books /
-- Open Library hit — a graded reader ("1984" by Michael Dean) and a study guide
-- ("Crime and Punishment" by James Lamar Roberts). analyze-novel now anchors bare
-- canon titles on canon_books' author; this repairs the rows already cached.
-- Non-destructive and idempotent: nothing is deleted, every statement is guarded.

-- 1) Relabel the wrong rows and free the /book/1984 and /book/crime-and-punishment slugs.
UPDATE public.novel_analyses
   SET title = '1984 (graded reader)', slug = '1984-graded-reader',
       analysis = jsonb_set(analysis, '{title}', '"1984 (graded reader)"')
 WHERE cache_key = 'v3|1984||michael dean' AND title = '1984';

UPDATE public.novel_analyses
   SET title = 'Crime and Punishment (study guide)', slug = 'crime-and-punishment-study-guide',
       analysis = jsonb_set(analysis, '{title}', '"Crime and Punishment (study guide)"')
 WHERE cache_key = 'v3|crime and punishment||james lamar roberts' AND title = 'Crime and Punishment';

-- 2) The bare "1984" key (one reader has it shelved) now serves Orwell's analysis.
UPDATE public.novel_analyses b
   SET analysis = o.analysis, title = o.title, author = o.author, model = o.model
  FROM public.novel_analyses o
 WHERE b.cache_key = 'v3|1984||' AND o.cache_key = 'v3|1984||george orwell'
   AND b.analysis->>'author' IS DISTINCT FROM o.analysis->>'author';

-- 3) Orwell's row owns /book/1984.
UPDATE public.novel_analyses SET slug = '1984'
 WHERE cache_key = 'v3|1984||george orwell' AND slug IS NULL
   AND NOT EXISTS (SELECT 1 FROM public.novel_analyses WHERE slug = '1984');

-- 4) The bare "Crime and Punishment" key serves Dostoevsky's analysis once that
--    row exists (it is generated by a normal "Crime and Punishment by Fyodor
--    Dostoevsky" request after step 1 frees the slug; no-op until then).
UPDATE public.novel_analyses b
   SET analysis = o.analysis, title = o.title, author = o.author, model = o.model
  FROM public.novel_analyses o
 WHERE b.cache_key = 'v3|crime and punishment||' AND o.cache_key = 'v3|crime and punishment||fyodor dostoevsky'
   AND b.analysis->>'author' IS DISTINCT FROM o.analysis->>'author';
